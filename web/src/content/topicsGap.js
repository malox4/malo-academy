import { teach, arc } from "./pedagogy.js";

function T(x) {
  const {
    term, not, about, fig,
    what, purpose, howIntro, how, howSteps,
    whatFig, howFig, purposeFig, exampleFig,
    exampleTitle, exampleHeading, example, exampleNote,
    mistakesIntro, mistakes, cases, practice, to, cta,
    ...meta
  } = x;
  if (term) {
    return {
      ...meta,
      sections: teach({
        term, not, about, fig: fig || whatFig,
        purpose, purposeFig, howIntro, how: how || howSteps, howFig,
        exampleTitle: exampleTitle || exampleHeading,
        example, exampleNote, exampleFig, mistakesIntro, mistakes, cases, practice, to, cta,
      }),
    };
  }
  return {
    ...meta,
    sections: arc({
      what, purpose, howIntro, howSteps, whatFig, howFig, purposeFig, exampleFig,
      exampleHeading, example, exampleNote, mistakesIntro, mistakes, cases,
      practice, to, cta,
    }),
  };
}

